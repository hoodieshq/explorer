// Build-time codegen from the sha-pinned codama-fixtures tarball; re-run after bumping the pin.
// Literal DOCUMENT types exist because TypeScript widens JSON imports and codama ships no
// target/types equivalent; renderers-js clients feed the tests' type-only AsDecoded imports.
import { renderVisitor } from '@codama/renderers-js';
import { visit } from 'codama';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const OUT_DIR = fileURLToPath(new URL('../__tests__/functional/generated/', import.meta.url));
const IDLS = 'codama-fixtures/packages/dynamic-client/test/programs/idls';

const DOCUMENT_LITERALS = [{ idl: `${IDLS}/blog-idl.json`, typeName: 'BlogIdl', valueName: 'blogIdl' }];

// codama rejects some stress fixtures (circular defaults, invalid deps) — reported, never silent
const RENDERED_CLIENTS = [
    'associated-token-account-idl.json',
    'blog-idl.json',
    'circular-account-refs-idl.json',
    'collection-types-idl.json',
    'custom-resolvers-test-idl.json',
    'example-idl.json',
    'mpl-token-metadata-idl.json',
    'pmp-idl.json',
    'sas-idl.json',
    'system-program-idl.json',
    'token-2022-idl.json',
    'token-idl.json',
].map(file => ({ idl: `${IDLS}/${file}`, out: file.replace('-idl.json', '-client') }));

const loadIdl = idl => JSON.parse(readFileSync(require.resolve(idl), 'utf8'));

mkdirSync(OUT_DIR, { recursive: true });
for (const { idl, typeName, valueName } of DOCUMENT_LITERALS) {
    const literal = JSON.stringify(loadIdl(idl), null, 4);
    const out = `${valueName.replace(/Idl$/, '')}-idl.ts`;
    writeFileSync(
        join(OUT_DIR, out),
        `// Generated by scripts/generate-codama-types.mjs from ${idl} — do not edit, re-run the script.

/** The document as a literal type — getDecodedData payload inference reads names/formats from it. */
export type ${typeName} = ${literal};

/** The same document as a literal-typed value — createCodamaIdlClient(${valueName}) infers with no generics. */
export const ${valueName}: ${typeName} = ${literal};
`,
    );
    console.log('generated', out);
}

for (const { idl, out } of RENDERED_CLIENTS) {
    try {
        await visit(
            loadIdl(idl),
            renderVisitor(join(OUT_DIR, out), { deleteFolderBeforeRendering: true, formatCode: false }),
        );
        console.log('rendered', out);
    } catch (cause) {
        console.warn(`skipped ${out} — renderers-js rejected the document: ${cause.message}`);
    }
}
