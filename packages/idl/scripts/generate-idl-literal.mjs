// Emits literal IDL types from anchor build output — payload inference (infer.ts) only works on
// literal types, and TS cannot derive them from runtime JSON, so the document is written out as a
// type (truthful to target/idl/*.json: original casing, real discriminators — unlike anchor's
// camelCase target/types view). Refresh: pnpm run build:programs, then node scripts/generate-idl-literal.mjs.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);

const PROGRAMS = [
    {
        out: '../src/__tests__/generated/simple.literal.ts',
        pkg: '@explorer/idl-program-simple',
        typeName: 'SimpleIdl',
    },
];

for (const { out, pkg, typeName } of PROGRAMS) {
    const literal = JSON.stringify(JSON.parse(readFileSync(require.resolve(pkg), 'utf8')), null, 4);
    const outPath = fileURLToPath(new URL(out, import.meta.url));
    writeFileSync(
        outPath,
        `// Generated by scripts/generate-idl-literal.mjs from ${pkg} — do not edit, re-run the script.

/** The document as a literal type — getDecodedData payload inference reads arg/field types from it. */
export type ${typeName} = ${literal};
`,
    );
    console.log(`generated ${outPath}`);
}
